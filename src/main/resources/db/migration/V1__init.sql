-- Tejas Photography - initial schema (PostgreSQL / Neon)
-- Flyway runs this automatically on the first start; Hibernate only VALIDATES it afterwards.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(100)  NOT NULL,
    email       VARCHAR(150)  NOT NULL,
    phone       VARCHAR(20)   NOT NULL,
    password    VARCHAR(255)  NOT NULL,                -- BCrypt hash, never plain text
    role        VARCHAR(20)   NOT NULL,                -- USER | ADMIN
    enabled     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE inquiries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        REFERENCES users (id) ON DELETE SET NULL,   -- NULL = anonymous visitor
    name                VARCHAR(100)  NOT NULL,
    phone               VARCHAR(20)   NOT NULL,                                   -- +<countrycode><number>
    email               VARCHAR(150),
    event_date          DATE,                                                     -- requested shoot date
    service             VARCHAR(100),
    message             VARCHAR(2000),
    status              VARCHAR(20)   NOT NULL DEFAULT 'NEW',                     -- NEW | CONFIRMED | REJECTED
    whatsapp_status     VARCHAR(20)   NOT NULL DEFAULT 'NOT_SENT',                -- NOT_SENT | SENT | FAILED | DISABLED
    whatsapp_message_id VARCHAR(120),
    whatsapp_error      VARCHAR(500),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    confirmed_at        TIMESTAMPTZ,
    CONSTRAINT ck_inquiry_status CHECK (status IN ('NEW', 'CONFIRMED', 'REJECTED')),
    CONSTRAINT ck_inquiry_wa CHECK (whatsapp_status IN ('NOT_SENT', 'SENT', 'FAILED', 'DISABLED'))
);

CREATE INDEX idx_inquiry_date_status ON inquiries (event_date, status);
CREATE INDEX idx_inquiry_user        ON inquiries (user_id);
CREATE INDEX idx_inquiry_created     ON inquiries (created_at DESC);
